import 'dart:convert';
import 'dart:io';

Future<void> main() async {
  final configFile = File('.dart_tool/package_config.json');
  final config =
      jsonDecode(configFile.readAsStringSync()) as Map<String, dynamic>;
  final pkg = (config['packages'] as List)
      .cast<Map<String, dynamic>>()
      .firstWhere((p) => p['name'] == 'font_awesome_flutter');
  var rootUri = pkg['rootUri'] as String;
  if (!rootUri.endsWith('/')) rootUri = '$rootUri/';
  final root = configFile.absolute.uri.resolve(rootUri);
  final src = File.fromUri(
    root.resolve('lib/font_awesome_flutter.dart'),
  ).readAsStringSync();

  final decl = RegExp(
    r'  /// (.+) icon\n  ///\n  /// https://[^\n]*\n  /// ([^\n]*)\n'
    r'  static const FaIconData (\w+) = FaIconData\(',
  );
  final entries = <String>[];
  final seen = <String>{};
  for (final m in decl.allMatches(src)) {
    final label = m.group(1)!;
    final terms = m.group(2)!;
    final name = m.group(3)!;
    if (!seen.add(name)) continue;
    entries.add(
      "  '$name': FaIconEntry(FontAwesomeIcons.$name, "
      "${_q(label)}, ${_q(terms)}),",
    );
  }
  if (entries.length < 1000) {
    stderr.writeln('Only ${entries.length} icons parsed — format changed?');
    exit(1);
  }

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_fa_icon_registry.dart — do not edit.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln(
      "import 'package:font_awesome_flutter/font_awesome_flutter.dart';",
    )
    ..writeln()
    ..writeln('/// One Font Awesome icon: [label] is e.g. "Solid House" and')
    ..writeln('/// [terms] the comma-separated search keywords.')
    ..writeln('class FaIconEntry {')
    ..writeln('  final FaIconData icon;')
    ..writeln('  final String label;')
    ..writeln('  final String terms;')
    ..writeln('  const FaIconEntry(this.icon, this.label, this.terms);')
    ..writeln('}')
    ..writeln()
    ..writeln('/// Keyed by the `FontAwesomeIcons` identifier (stored as')
    ..writeln('/// `fa:<name>`).')
    ..writeln('const Map<String, FaIconEntry> faIconRegistry = {')
    ..writeAll(entries, '\n')
    ..writeln()
    ..writeln('};');
  File('lib/widgets/fa_icon_registry.g.dart').writeAsStringSync('$out');
  stdout.writeln('Wrote ${entries.length} icons.');
}

String _q(String s) =>
    "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$')}'";
